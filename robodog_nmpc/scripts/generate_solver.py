"""Generate the C code of the NMPC solver from config.yaml (run after changing a [codegen] setting).

    config/config.yaml --> validate --> srbd_ocp.build_ocp() --> acados C code + shared library

Only the C solver is generated and compiled (no Python/Cython interface): this is what the C++ class
links against. Because the solver has a fixed name (codegen.solver_name), the generated files and C
functions keep the same names whatever the configuration is, e.g. for solver_name = srbd_nmpc:
    acados_solver_srbd_nmpc.h / .c             C API: create, set, solve, get, free
    libacados_ocp_solver_srbd_nmpc.so          compiled solver
    srbd_nmpc_model/, _cost/, _constraints/    CasADi-generated model, cost and constraint functions

Safety: the output folder is deleted and recreated on every run. To make that safe, it must be a
sub-folder of the package, and an existing folder is only deleted if it contains the marker file that
this script writes. A folder this script did not create (e.g. config/) is never deleted.

Usage (from anywhere; needs ACADOS_SOURCE_DIR and LD_LIBRARY_PATH, see README):
    python scripts/generate_solver.py [--config path/to/config.yaml]
"""
import argparse
import os
import shutil
import sys

from srbd_ocp import ConfigError, load_config, build_ocp

PKG_ROOT = os.path.realpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
MARKER = '.generated_by_generate_solver'

# [codegen] settings that are compiled into the solver (codegen.export_dir only says where it goes).
# They are written to <solver_name>_codegen_config.h; the C++ class compares them with the YAML at
# initialize() and refuses to start on any difference (stale solver -> rerun this script).
CODEGEN_KEYS = [('horizon', 'N'), ('horizon', 'dt'),
                ('friction', 'model'), ('friction', 'polygon_sides'),
                *[('solver', k) for k in ('nlp_solver_type', 'qp_solver', 'hessian_approx', 'integrator_type',
                                          'sim_method_num_stages', 'sim_method_num_steps', 'globalization',
                                          'nlp_solver_max_iter', 'qp_solver_iter_max')],
                ('codegen', 'solver_name')]
REAL_KEYS = {('horizon', 'dt'), ('friction', 'mu')}     # written as DOUBLE, all other numbers as INT


class GenerateError(RuntimeError):
    pass


def check_acados():
    """Fail early with a clear message if acados is not set up (instead of a compiler error later)."""
    src = os.environ.get('ACADOS_SOURCE_DIR')
    if not src:
        raise GenerateError("ACADOS_SOURCE_DIR is not set (e.g. export ACADOS_SOURCE_DIR=$HOME/acados)")
    lib = os.path.join(src, 'lib', 'libacados.so')
    if not os.path.isfile(lib):
        raise GenerateError(f"acados library not found: {lib} (is acados built and installed there?)")


def resolve_export_dir(export_dir):
    """Absolute output folder: must be strictly inside the package, and if it already exists it must
    carry the marker of a previous generation (so nothing else can be deleted by accident)."""
    if os.path.isabs(export_dir):
        raise GenerateError(f"codegen.export_dir must be relative to the package, got '{export_dir}'")
    path = os.path.realpath(os.path.join(PKG_ROOT, export_dir))
    if os.path.commonpath([path, PKG_ROOT]) != PKG_ROOT or path == PKG_ROOT:
        raise GenerateError(f"codegen.export_dir '{export_dir}' must be a sub-folder inside the package "
                            f"({PKG_ROOT})")
    if os.path.exists(path) and not os.path.isfile(os.path.join(path, MARKER)):
        raise GenerateError(f"codegen.export_dir '{export_dir}' exists and was not created by this script "
                            f"(no {MARKER}); refusing to delete it. Choose another folder or remove it by hand.")
    return path


def codegen_keys(cfg):
    """CODEGEN_KEYS, plus friction.mu when it is compiled in (pyramid model only)."""
    return CODEGEN_KEYS + ([('friction', 'mu')] if cfg['friction']['model'] == 'pyramid' else [])


def write_codegen_config_header(cfg, name, export_dir):
    """Write the [codegen] values as one list macro, NAME_CODEGEN_CONFIG(INT, DOUBLE, STRING), that the
    C++ class expands to compare every entry with the YAML. Doubles use repr(): exact round trip."""
    entries = []
    for group, key in codegen_keys(cfg):
        v = cfg[group][key]                       # validated: strings are choices / C identifiers
        if isinstance(v, str):
            entries.append(f'STRING("{group}", "{key}", "{v}")')
        elif (group, key) in REAL_KEYS:           # also when written as an int in the YAML (dt: 1)
            entries.append(f'DOUBLE("{group}", "{key}", {float(v)!r})')
        else:
            entries.append(f'INT("{group}", "{key}", {v})')
    guard = f"{name.upper()}_CODEGEN_CONFIG_H_"
    body = " \\\n".join(f"    {e}" for e in entries)
    text = (f"/* Generated by scripts/generate_solver.py, do not edit.\n"
            f" * The [codegen] settings this solver was generated with. The C++ class compares them with\n"
            f" * config.yaml at initialize(); on any difference, rerun scripts/generate_solver.py. */\n"
            f"#ifndef {guard}\n#define {guard}\n\n"
            f"#define {name.upper()}_CODEGEN_CONFIG(INT, DOUBLE, STRING) \\\n{body}\n\n"
            f"#endif  /* {guard} */\n")
    with open(os.path.join(export_dir, f"{name}_codegen_config.h"), 'w') as f:
        f.write(text)


def generate(config_path):
    cfg = load_config(config_path)                    # 1. validate the whole config (needs no acados)
    export_dir = resolve_export_dir(cfg['codegen']['export_dir'])   # 2. safe output folder
    check_acados()                                    # 3. acados environment
    ocp = build_ocp(cfg)

    from acados_template import AcadosOcpSolver      # after the checks: clear errors come first
    if os.path.isdir(export_dir):
        shutil.rmtree(export_dir)                     # start clean: no stale files from older configs
    os.makedirs(export_dir)
    with open(os.path.join(export_dir, MARKER), 'w') as f:     # no paths: solver/ is committed to git
        f.write("Generated by scripts/generate_solver.py.\n"
                "This whole folder is deleted and recreated on every run; do not edit files here.\n")
    ocp.code_gen_options.code_export_directory = export_dir
    ocp.code_gen_options.json_file = f"{ocp.name}.json"

    AcadosOcpSolver.generate(ocp, verbose=False)      # C code (CasADi functions + acados templates)
    write_codegen_config_header(cfg, ocp.name, export_dir)
    AcadosOcpSolver.build(export_dir, with_cython=False, verbose=False)   # -> lib*.so, no Python part
    if not os.path.isfile(os.path.join(export_dir, f"libacados_ocp_solver_{ocp.name}.so")):
        raise GenerateError("build finished but the solver library is missing (see compiler output above)")
    return cfg, ocp, export_dir


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--config', default=os.path.join(PKG_ROOT, 'config', 'config.yaml'))
    args = ap.parse_args()

    try:
        cfg, ocp, export_dir = generate(os.path.abspath(args.config))
    except (ConfigError, GenerateError, FileNotFoundError) as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)

    print(f"solver '{ocp.name}' generated from {args.config}")
    print(f"  N = {cfg['horizon']['N']}, dt = {cfg['horizon']['dt']} s, friction = {cfg['friction']['model']}, "
          f"{cfg['solver']['nlp_solver_type']}")
    print(f"  output: {os.path.relpath(export_dir, PKG_ROOT)}/")
    for f in sorted(os.listdir(export_dir)):
        if not f.endswith('.o') and f != MARKER:
            print(f"    {f}{'/' if os.path.isdir(os.path.join(export_dir, f)) else ''}")
